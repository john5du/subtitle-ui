func (s *Store) copyTableRowsTx(tx *sql.Tx, source *Store, tableName string, columns []string, orderBy string) (int, error) {
	selectQuery := `SELECT ` + strings.Join(columns, ", ") + ` FROM ` + tableName
	if strings.TrimSpace(orderBy) != "" {
		selectQuery += ` ORDER BY ` + orderBy
	}

	rows, err := source.query(selectQuery)
	if err != nil {
		return 0, fmt.Errorf("query sqlite %s: %w", tableName, err)
	}
	defer rows.Close()

	insertQuery := `INSERT INTO ` + tableName + `(` + strings.Join(columns, ", ") + `) VALUES(` + placeholders(len(columns)) + `)`
	values := make([]any, len(columns))
	scanTargets := make([]any, len(columns))
	for i := range scanTargets {
		scanTargets[i] = &values[i]
	}

	count := 0
	for rows.Next() {
		for i := range values {
			values[i] = nil
		}
		if err := rows.Scan(scanTargets...); err != nil {
			return count, fmt.Errorf("scan sqlite %s: %w", tableName, err)
		}
		for i, value := range values {
			if raw, ok := value.([]byte); ok {
				values[i] = string(raw)
			}
		}
		if _, err := s.execTx(tx, insertQuery, values...); err != nil {
			return count, fmt.Errorf("insert postgres %s: %w", tableName, err)
		}
		count += 1
	}
	if err := rows.Err(); err != nil {
		return count, err
	}
	return count, nil
}

func backupSQLiteSource(dbPath string) (string, error) {
	timestamp := time.Now().UTC().Format("20060102T150405.000000000Z")
	backupPath := dbPath + ".backup-" + timestamp
	copied := []string{}

	if err := copyFileExclusive(dbPath, backupPath); err != nil {
		return "", err
	}
	copied = append(copied, backupPath)

	for _, suffix := range []string{"-wal", "-shm"} {
		sourcePath := dbPath + suffix
		if _, err := os.Stat(sourcePath); errors.Is(err, os.ErrNotExist) {
			continue
		} else if err != nil {
			removeFiles(copied)
			return "", err
		}

		targetPath := backupPath + suffix
		if err := copyFileExclusive(sourcePath, targetPath); err != nil {
			removeFiles(copied)
			return "", err
		}
		copied = append(copied, targetPath)
	}

	return backupPath, nil
}

func copyFileExclusive(sourcePath string, targetPath string) error {
	info, err := os.Stat(sourcePath)
	if err != nil {
		return err
	}
	if info.IsDir() {
		return fmt.Errorf("source is a directory: %s", sourcePath)
	}

	source, err := os.Open(sourcePath)
	if err != nil {
		return err
	}
	defer source.Close()

	target, err := os.OpenFile(targetPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, info.Mode().Perm())
	if err != nil {
		return err
	}
	success := false
	defer func() {
		_ = target.Close()
		if !success {
			_ = os.Remove(targetPath)
		}
	}()

	if _, err := io.Copy(target, source); err != nil {
		return err
	}
	if err := target.Sync(); err != nil {
		return err
	}
	if err := target.Close(); err != nil {
		return err
	}
	success = true
	return nil
}

func removeFiles(paths []string) {
	for _, path := range paths {
		_ = os.Remove(path)
	}
}

func (s *Store) migrate() error {
	if _, err := s.exec(`
CREATE TABLE IF NOT EXISTS schema_migrations (
  version INTEGER PRIMARY KEY,
  applied_at TEXT NOT NULL
)`); err != nil {
		return err
	}

	applied, err := s.isMigrationApplied(1)
	if err != nil {
		return err
	}
	if !applied {
		tx, err := s.db.Begin()
		if err != nil {
			return err
		}
		defer func() {
			if err != nil {
				_ = tx.Rollback()
			}
		}()

		if err = s.execScriptTx(tx, s.migrationV1SQL()); err != nil {
			return fmt.Errorf("apply migration v1: %w", err)
		}
		if _, err = s.execTx(tx, `INSERT INTO schema_migrations(version, applied_at) VALUES(?, ?)`, 1, time.Now().UTC().Format(time.RFC3339Nano)); err != nil {
			return err
		}
		if err = tx.Commit(); err != nil {
			return err
		}
	}

	applied, err = s.isMigrationApplied(2)
	if err != nil {
		return err
	}
	if !applied {
		hasMediaType, err := s.hasColumn("videos", "media_type")
		if err != nil {
			return err
		}
		if !hasMediaType {
			if err := s.execScript(migrationV2); err != nil {
				return fmt.Errorf("apply migration v2: %w", err)
			}
		}
		if _, err = s.exec(`INSERT INTO schema_migrations(version, applied_at) VALUES(?, ?)`, 2, time.Now().UTC().Format(time.RFC3339Nano)); err != nil {
			return err
		}
	}

	applied, err = s.isMigrationApplied(3)
	if err != nil {
		return err
	}
	if !applied {
		hasPosterPath, err := s.hasColumn("videos", "poster_path")
		if err != nil {
			return err
		}
		if !hasPosterPath {
			if _, err := s.exec(migrationV3); err != nil {
				return fmt.Errorf("apply migration v3: %w", err)
			}
		}
		if _, err := s.exec(`INSERT INTO schema_migrations(version, applied_at) VALUES(?, ?)`, 3, time.Now().UTC().Format(time.RFC3339Nano)); err != nil {
			return err
		}
	}

	applied, err = s.isMigrationApplied(4)
	if err != nil {
		return err
	}
	if !applied {
		if err := s.execScript(migrationV4); err != nil {
			return fmt.Errorf("apply migration v4: %w", err)
		}
		if _, err := s.exec(`INSERT INTO schema_migrations(version, applied_at) VALUES(?, ?)`, 4, time.Now().UTC().Format(time.RFC3339Nano)); err != nil {
			return err
		}
	}

	applied, err = s.isMigrationApplied(5)
	if err != nil {
		return err
	}
	if !applied {
		hasSource, err := s.hasColumn("subtitles", "source")
		if err != nil {
			return err
		}
		if !hasSource {
			if _, err := s.exec(migrationV5AddSource); err != nil {
				return fmt.Errorf("apply migration v5 source: %w", err)
			}
		}
		hasSourceDetail, err := s.hasColumn("subtitles", "source_detail")
		if err != nil {
			return err
		}
		if !hasSourceDetail {
			if _, err := s.exec(migrationV5AddSourceDetail); err != nil {
				return fmt.Errorf("apply migration v5 source_detail: %w", err)
			}
		}
		if err := s.backfillSubtitleSources(); err != nil {
			return fmt.Errorf("backfill migration v5 subtitle sources: %w", err)
		}
		if _, err := s.exec(`INSERT INTO schema_migrations(version, applied_at) VALUES(?, ?)`, 5, time.Now().UTC().Format(time.RFC3339Nano)); err != nil {
			return err
		}
	}

	applied, err = s.isMigrationApplied(6)
	if err != nil {
		return err
	}
	if !applied {
		for _, column := range migrationV6VideoMetadataColumns {
			hasMetadataColumn, err := s.hasColumn("videos", column.name)
			if err != nil {
				return err
			}
			if !hasMetadataColumn {
				if _, err := s.exec(column.statement); err != nil {
					return fmt.Errorf("apply migration v6 %s: %w", column.name, err)
				}
			}
		}
		if _, err := s.exec(`INSERT INTO schema_migrations(version, applied_at) VALUES(?, ?)`, 6, time.Now().UTC().Format(time.RFC3339Nano)); err != nil {
			return err
		}
	}

	if s.dialect == dialectPostgres {
		if _, err := s.exec(`
CREATE TABLE IF NOT EXISTS data_migrations (
  name TEXT PRIMARY KEY,
  source TEXT NOT NULL DEFAULT '',
  applied_at TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT ''
)`); err != nil {
			return fmt.Errorf("create data migrations table: %w", err)
		}
	}

	return nil
}

