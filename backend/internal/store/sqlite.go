func (s *Store) attachSubtitles(videos []domain.Video) error {
	if len(videos) == 0 {
		return nil
	}

	placeholders := make([]string, len(videos))
	args := make([]any, len(videos))
	indexByID := make(map[string]int, len(videos))
	for i, v := range videos {
		placeholders[i] = "?"
		args[i] = v.ID
		indexByID[v.ID] = i
		videos[i].Subtitles = []domain.Subtitle{}
	}

	query := `SELECT video_id, id, path, file_name, language, format, size, mod_time, source, source_detail
FROM subtitles WHERE video_id IN (` + strings.Join(placeholders, ",") + `) ORDER BY file_name ASC`

	rows, err := s.query(query, args...)
	if err != nil {
		return err
	}
	defer rows.Close()

	for rows.Next() {
		var (
			videoID  string
			sub      domain.Subtitle
			modValue string
		)
		if err := rows.Scan(
			&videoID,
			&sub.ID,
			&sub.Path,
			&sub.FileName,
			&sub.Language,
			&sub.Format,
			&sub.Size,
			&modValue,
			&sub.Source,
			&sub.SourceDetail,
		); err != nil {
			return err
		}
		sub.ModTime = parseTimeOrNow(modValue)
		sub = normalizeSubtitleSource(sub)
		idx, ok := indexByID[videoID]
		if !ok {
			continue
		}
		videos[idx].Subtitles = append(videos[idx].Subtitles, sub)
	}
	return rows.Err()
}

func (s *Store) loadSubtitleSourcesTx(tx *sql.Tx, videoID string) (map[string]subtitleSourceInfo, error) {
	query := `SELECT path, source, source_detail FROM subtitles`
	args := []any{}
	if strings.TrimSpace(videoID) != "" {
		query += ` WHERE video_id = ?`
		args = append(args, videoID)
	}

	rows, err := s.queryTx(tx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	out := make(map[string]subtitleSourceInfo, 32)
	for rows.Next() {
		var (
			pathValue string
			info      subtitleSourceInfo
		)
		if err := rows.Scan(&pathValue, &info.Source, &info.SourceDetail); err != nil {
			return nil, err
		}
		info.Source = normalizeSubtitleSourceValue(info.Source)
		info.SourceDetail = strings.TrimSpace(info.SourceDetail)
		out[subtitlePathKey(pathValue)] = info
	}
	return out, rows.Err()
}

func mergeSubtitleSource(sub domain.Subtitle, existing map[string]subtitleSourceInfo) domain.Subtitle {
	source := strings.TrimSpace(sub.Source)
	detail := strings.TrimSpace(sub.SourceDetail)
	if source == "" || (normalizeSubtitleSourceValue(source) == domain.SubtitleSourceDirectory && detail == "") {
		if info, ok := existing[subtitlePathKey(sub.Path)]; ok {
			sub.Source = info.Source
			sub.SourceDetail = info.SourceDetail
			return normalizeSubtitleSource(sub)
		}
	}
	return normalizeSubtitleSource(sub)
}

func normalizeSubtitleSource(sub domain.Subtitle) domain.Subtitle {
	sub.Source = normalizeSubtitleSourceValue(sub.Source)
	sub.SourceDetail = strings.TrimSpace(sub.SourceDetail)
	return sub
}

func normalizeSubtitleSourceValue(source string) string {
	switch strings.ToLower(strings.TrimSpace(source)) {
	case domain.SubtitleSourceUpload:
		return domain.SubtitleSourceUpload
	case domain.SubtitleSourceGenerated:
		return domain.SubtitleSourceGenerated
	default:
		return domain.SubtitleSourceDirectory
	}
}

func subtitlePathKey(pathValue string) string {
	normalized := filepath.Clean(strings.TrimSpace(pathValue))
	normalized = strings.ReplaceAll(normalized, "\\", "/")
	return strings.ToLower(normalized)
}

func (s *Store) backfillSubtitleSources() error {
	type backfillInfo struct {
		targetPath   string
		source       string
		sourceDetail string
	}

	rows, err := s.query(
		`SELECT target_path, action, message
FROM operation_logs
WHERE status = 'ok'
  AND action IN ('upload', 'replace', 'convert')
  AND trim(target_path) != ''
ORDER BY timestamp ASC`,
	)
	if err != nil {
		return err
	}
	defer rows.Close()

	latestByPath := make(map[string]backfillInfo, 32)
	for rows.Next() {
		var targetPath, action, message string
		if err := rows.Scan(&targetPath, &action, &message); err != nil {
			return err
		}
		info := backfillInfo{targetPath: targetPath}
		switch action {
		case "convert":
			info.source = domain.SubtitleSourceGenerated
			info.sourceDetail = strings.TrimSpace(strings.TrimPrefix(message, "generated from "))
		default:
			info.source = domain.SubtitleSourceUpload
			info.sourceDetail = filepath.Base(targetPath)
		}
		latestByPath[subtitlePathKey(targetPath)] = info
	}
	if err := rows.Err(); err != nil {
		return err
	}

	for _, info := range latestByPath {
		if info.sourceDetail == "" || info.sourceDetail == "." {
			info.sourceDetail = filepath.Base(info.targetPath)
		}
		if _, err := s.exec(
			`UPDATE subtitles SET source = ?, source_detail = ? WHERE lower(path) = lower(?)`,
			info.source,
			info.sourceDetail,
			info.targetPath,
		); err != nil {
			return err
		}
	}
	return nil
}

func (s *Store) migrateInitialSQLiteData(sqlitePath string) error {
	if s.dialect != dialectPostgres {
		return nil
	}

	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	committed := false
	defer func() {
		if !committed {
			_ = tx.Rollback()
		}
	}()

	if _, err = s.execTx(tx, `SELECT pg_advisory_xact_lock(?)`, int64(93070001)); err != nil {
		return fmt.Errorf("lock sqlite import migration: %w", err)
	}

	applied, err := s.isDataMigrationAppliedTx(tx, sqliteInitialDataMigration)
	if err != nil {
		return err
	}
	if applied {
		if err := tx.Commit(); err != nil {
			return err
		}
		committed = true
		return nil
	}

	targetRows, err := s.businessRowCountTx(tx)
	if err != nil {
		return err
	}
	if targetRows > 0 {
		return fmt.Errorf("postgres database already contains %d business rows; refusing to import sqlite data without migration marker", targetRows)
	}

	sourcePath := strings.TrimSpace(sqlitePath)
	if sourcePath == "" {
		if err := s.insertDataMigrationMarkerTx(tx, sqliteInitialDataMigration, "", "sqlite source not configured"); err != nil {
			return err
		}
		if err := tx.Commit(); err != nil {
			return err
		}
		committed = true
		return nil
	}

	absSourcePath, err := filepath.Abs(sourcePath)
	if err != nil {
		return err
	}
	stat, err := os.Stat(absSourcePath)
	if errors.Is(err, os.ErrNotExist) {
		if err := s.insertDataMigrationMarkerTx(tx, sqliteInitialDataMigration, absSourcePath, "sqlite source not found"); err != nil {
			return err
		}
		if err := tx.Commit(); err != nil {
			return err
		}
		committed = true
		return nil
	}
	if err != nil {
		return err
	}
	if stat.IsDir() {
		return fmt.Errorf("sqlite migration source is a directory: %s", absSourcePath)
	}
	backupPath, err := backupSQLiteSource(absSourcePath)
	if err != nil {
		return fmt.Errorf("backup sqlite migration source: %w", err)
	}

	source, err := openSQLite(absSourcePath)
	if err != nil {
		return fmt.Errorf("open sqlite migration source: %w", err)
	}
	defer func() {
		_ = source.Close()
	}()

	sourceRows, err := source.businessRowCount()
	if err != nil {
		return err
	}
	if sourceRows == 0 {
		if err := s.insertDataMigrationMarkerTx(tx, sqliteInitialDataMigration, absSourcePath, "sqlite source empty; backup="+backupPath); err != nil {
			return err
		}
		if err := tx.Commit(); err != nil {
			return err
		}
		committed = true
		return nil
	}

	if _, err := s.copyTableRowsTx(tx, source, "videos", []string{
		"id", "path", "directory", "file_name", "title", "original_title", "year", "imdb_id", "tmdb_id", "media_type", "metadata_source", "series_title", "series_original_title", "series_imdb_id", "series_tmdb_id", "poster_path", "updated_at",
	}, "id"); err != nil {
		return err
	}
	if _, err := s.copyTableRowsTx(tx, source, "subtitles", []string{
		"id", "video_id", "path", "file_name", "language", "format", "size", "mod_time", "updated_at", "source", "source_detail",
	}, "id"); err != nil {
		return err
	}
	if _, err := s.copyTableRowsTx(tx, source, "scan_runs", []string{
		"id", "started_at", "finished_at", "video_count", "error",
	}, "id"); err != nil {
		return err
	}
	if _, err := s.copyTableRowsTx(tx, source, "operation_logs", []string{
		"id", "timestamp", "action", "video_id", "target_path", "backup_path", "status", "message",
	}, "id"); err != nil {
		return err
	}
	if _, err := s.copyTableRowsTx(tx, source, "app_settings", []string{
		"key", "value", "updated_at",
	}, "key"); err != nil {
		return err
	}
	if _, err := s.execTx(tx, `SELECT setval(pg_get_serial_sequence('scan_runs', 'id'), COALESCE((SELECT MAX(id) FROM scan_runs), 1), (SELECT MAX(id) FROM scan_runs) IS NOT NULL)`); err != nil {
		return fmt.Errorf("reset scan_runs identity: %w", err)
	}

	if err := s.insertDataMigrationMarkerTx(tx, sqliteInitialDataMigration, absSourcePath, fmt.Sprintf("imported %d sqlite business rows; backup=%s", sourceRows, backupPath)); err != nil {
		return err
	}
	if err := tx.Commit(); err != nil {
		return err
	}
	committed = true
	return nil
}

