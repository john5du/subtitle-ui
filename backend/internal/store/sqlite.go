type Driver string

const (
	DriverSQLite   Driver = "sqlite"
	DriverPostgres Driver = "postgres"
)

type OpenOptions struct {
	Driver      Driver
	SQLitePath  string
	PostgresURL string
}

type sqlDialect string

const (
	dialectSQLite   sqlDialect = "sqlite"
	dialectPostgres sqlDialect = "postgres"
)

const sqliteInitialDataMigration = "sqlite_initial_import"

func Open(dbPath string) (*Store, error) {
	return OpenWithOptions(OpenOptions{
		Driver:     DriverSQLite,
		SQLitePath: dbPath,
	})
}

func OpenWithOptions(options OpenOptions) (*Store, error) {
	driver := options.Driver
	if driver == "" {
		if strings.TrimSpace(options.PostgresURL) != "" {
			driver = DriverPostgres
		} else {
			driver = DriverSQLite
		}
	}

	switch driver {
	case DriverPostgres:
		return openPostgres(options.PostgresURL, options.SQLitePath)
	case DriverSQLite:
		return openSQLite(options.SQLitePath)
	default:
		return nil, fmt.Errorf("unsupported database driver %q", driver)
	}
}

func openSQLite(dbPath string) (*Store, error) {
	absPath, err := filepath.Abs(dbPath)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(filepath.Dir(absPath), 0o755); err != nil {
		return nil, err
	}

	db, err := sql.Open("sqlite", absPath)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(1)

	if _, err := db.Exec(`PRAGMA foreign_keys = ON;`); err != nil {
		_ = db.Close()
		return nil, err
	}

	s := &Store{db: db, dialect: dialectSQLite}
	if err := s.migrate(); err != nil {
		_ = db.Close()
		return nil, err
	}
	return s, nil
}

func openPostgres(databaseURL string, sqlitePath string) (*Store, error) {
	dsn := strings.TrimSpace(databaseURL)
	if dsn == "" {
		return nil, errors.New("postgres database URL is required")
	}

	db, err := sql.Open("pgx", dsn)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(10)
	db.SetMaxIdleConns(5)
	db.SetConnMaxLifetime(time.Hour)

	if err := db.Ping(); err != nil {
		_ = db.Close()
		return nil, err
	}

	s := &Store{db: db, dialect: dialectPostgres}
	if err := s.migrate(); err != nil {
		_ = db.Close()
		return nil, err
	}
	if err := s.migrateInitialSQLiteData(sqlitePath); err != nil {
		_ = db.Close()
		return nil, err
	}
	return s, nil
}

func (s *Store) Close() error {
	if s == nil || s.db == nil {
		return nil
	}
	return s.db.Close()
}

func (s *Store) DatabaseType() string {
	if s == nil {
		return string(dialectSQLite)
	}
	if s.dialect == dialectPostgres {
		return string(dialectPostgres)
	}
	return string(dialectSQLite)
}

func (s *Store) exec(query string, args ...any) (sql.Result, error) {
	return s.db.Exec(s.rebind(query), args...)
}

func (s *Store) query(query string, args ...any) (*sql.Rows, error) {
	return s.db.Query(s.rebind(query), args...)
}

func (s *Store) queryRow(query string, args ...any) *sql.Row {
	return s.db.QueryRow(s.rebind(query), args...)
}

func (s *Store) execTx(tx *sql.Tx, query string, args ...any) (sql.Result, error) {
	return tx.Exec(s.rebind(query), args...)
}

func (s *Store) execScript(query string) error {
	for _, statement := range strings.Split(query, ";") {
		statement = strings.TrimSpace(statement)
		if statement == "" {
			continue
		}
		if _, err := s.exec(statement); err != nil {
			return err
		}
	}
	return nil
}

func (s *Store) execScriptTx(tx *sql.Tx, query string) error {
	for _, statement := range strings.Split(query, ";") {
		statement = strings.TrimSpace(statement)
		if statement == "" {
			continue
		}
		if _, err := s.execTx(tx, statement); err != nil {
			return err
		}
	}
	return nil
}

func (s *Store) queryTx(tx *sql.Tx, query string, args ...any) (*sql.Rows, error) {
	return tx.Query(s.rebind(query), args...)
}

func (s *Store) queryRowTx(tx *sql.Tx, query string, args ...any) *sql.Row {
	return tx.QueryRow(s.rebind(query), args...)
}

func (s *Store) rebind(query string) string {
	if s.dialect != dialectPostgres {
		return query
	}

	var b strings.Builder
	b.Grow(len(query) + 8)
	index := 1
	for _, r := range query {
		if r == '?' {
			b.WriteByte('$')
			b.WriteString(fmt.Sprint(index))
			index += 1
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

func placeholders(count int) string {
	if count <= 0 {
		return ""
	}
	out := make([]string, count)
	for i := range out {
		out[i] = "?"
	}
	return strings.Join(out, ",")
}

func (s *Store) insertPrefix() string {
	if s.dialect == dialectSQLite {
		return "INSERT OR REPLACE"
	}
	return "INSERT"
}

func (s *Store) migrationV1SQL() string {
	if s.dialect == dialectPostgres {
		return migrationV1Postgres
	}
	return migrationV1
}

func (s *Store) SaveScanResult(videos []domain.Video, startedAt time.Time, finishedAt time.Time, scanErr string) error {
	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	defer func() {
		if err != nil {
			_ = tx.Rollback()
		}
	}()

	_, err = s.execTx(
		tx,
		`INSERT INTO scan_runs(started_at, finished_at, video_count, error) VALUES(?, ?, ?, ?)`,
		startedAt.UTC().Format(time.RFC3339Nano),
		finishedAt.UTC().Format(time.RFC3339Nano),
		len(videos),
		scanErr,
	)
	if err != nil {
		return err
	}

	if scanErr == "" || len(videos) > 0 {
		existingSubtitleSources, err := s.loadSubtitleSourcesTx(tx, "")
		if err != nil {
			return err
		}
		if _, err = s.execTx(tx, `DELETE FROM subtitles`); err != nil {
			return err
		}
		if _, err = s.execTx(tx, `DELETE FROM videos`); err != nil {
			return err
		}

		for _, video := range videos {
			_, err = s.execTx(
				tx,
				s.insertPrefix()+` INTO videos(id, path, directory, file_name, title, original_title, year, imdb_id, tmdb_id, media_type, metadata_source, series_title, series_original_title, series_imdb_id, series_tmdb_id, poster_path, updated_at)
VALUES(?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
				video.ID,
				video.Path,
				video.Directory,
				video.FileName,
				video.Title,
				video.OriginalTitle,
				video.Year,
				video.ImdbID,
				video.TmdbID,
				defaultMediaType(video.MediaType),
				video.MetadataSource,
				video.SeriesTitle,
				video.SeriesOriginalTitle,
				video.SeriesImdbID,
				video.SeriesTmdbID,
				video.PosterPath,
				video.UpdatedAt.UTC().Format(time.RFC3339Nano),
			)
			if err != nil {
				return err
			}

			for _, sub := range video.Subtitles {
				sub = mergeSubtitleSource(sub, existingSubtitleSources)
				_, err = s.execTx(
					tx,
					s.insertPrefix()+` INTO subtitles(id, video_id, path, file_name, language, format, size, mod_time, updated_at, source, source_detail)
VALUES(?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
					sub.ID,
					video.ID,
					sub.Path,
					sub.FileName,
					sub.Language,
					sub.Format,
					sub.Size,
					sub.ModTime.UTC().Format(time.RFC3339Nano),
					video.UpdatedAt.UTC().Format(time.RFC3339Nano),
					sub.Source,
					sub.SourceDetail,
				)
				if err != nil {
					return err
				}
			}
		}
	}

	return tx.Commit()
}

func (s *Store) ListVideos(query string, mediaType string, directory string, page int, pageSize int, sortBy string, sortOrder string) ([]domain.Video, int, error) {
	if page <= 0 {
		page = 1
	}
	if pageSize <= 0 {
		pageSize = 30
	}
	if pageSize > 200 {
		pageSize = 200
	}

	baseQuery := `SELECT id, path, directory, file_name, title, original_title, year, imdb_id, tmdb_id, media_type, metadata_source, series_title, series_original_title, series_imdb_id, series_tmdb_id, poster_path, updated_at FROM videos`
	args := []any{}
	conditions := make([]string, 0, 2)

	needle := strings.TrimSpace(strings.ToLower(query))
	if needle != "" {
		conditions = append(conditions, `(lower(title) LIKE ? OR lower(original_title) LIKE ? OR lower(series_title) LIKE ? OR lower(series_original_title) LIKE ? OR lower(path) LIKE ?)`)
		like := "%" + needle + "%"
		args = append(args, like, like, like, like, like)
	}
	typeFilter := normalizeMediaType(mediaType)
	if typeFilter != "" {
		conditions = append(conditions, `media_type = ?`)
		args = append(args, typeFilter)
	}
	dirFilter := strings.TrimSpace(directory)
	if dirFilter != "" {
		normalized := strings.ToLower(strings.ReplaceAll(strings.TrimRight(dirFilter, "/\\"), "\\", "/"))
		conditions = append(conditions, `(lower(path) LIKE ? OR lower(replace(path, '\', '/')) LIKE ?)`)
		args = append(args, strings.ToLower(strings.TrimRight(dirFilter, "/\\"))+"%", normalized+"%")
	}
	if len(conditions) > 0 {
		baseQuery += ` WHERE ` + strings.Join(conditions, " AND ")
	}

	countQuery := `SELECT COUNT(1) FROM videos`
	if len(conditions) > 0 {
		countQuery += ` WHERE ` + strings.Join(conditions, " AND ")
	}
	total, err := s.countByQuery(countQuery, args)
	if err != nil {
		return nil, 0, err
	}

	offset := (page - 1) * pageSize
	baseQuery += " " + s.buildVideoOrderBy(sortBy, sortOrder) + ` LIMIT ? OFFSET ?`
	args = append(args, pageSize, offset)

	rows, err := s.query(baseQuery, args...)
	if err != nil {
		return nil, 0, err
	}
	defer rows.Close()

	out := make([]domain.Video, 0, 64)
	for rows.Next() {
		video, err := scanVideoRow(rows)
		if err != nil {
			return nil, 0, err
		}
		out = append(out, video)
	}
	if err := rows.Err(); err != nil {
		return nil, 0, err
	}

	// Batch-load subtitles after the main rows cursor is closed to avoid
	// single-connection SQLite deadlocks.
	if err := s.attachSubtitles(out); err != nil {
		return nil, 0, err
	}

	return out, total, nil
}

func (s *Store) GetVideo(videoID string) (domain.Video, bool, error) {
	row := s.queryRow(
		`SELECT id, path, directory, file_name, title, original_title, year, imdb_id, tmdb_id, media_type, metadata_source, series_title, series_original_title, series_imdb_id, series_tmdb_id, poster_path, updated_at FROM videos WHERE id = ?`,
		videoID,
	)

	var (
		video      domain.Video
		posterPath string
		updatedRaw string
	)
	err := row.Scan(
		&video.ID,
		&video.Path,
		&video.Directory,
		&video.FileName,
		&video.Title,
		&video.OriginalTitle,
		&video.Year,
		&video.ImdbID,
		&video.TmdbID,
		&video.MediaType,
		&video.MetadataSource,
		&video.SeriesTitle,
		&video.SeriesOriginalTitle,
		&video.SeriesImdbID,
		&video.SeriesTmdbID,
		&posterPath,
		&updatedRaw,
	)
	if errors.Is(err, sql.ErrNoRows) {
		return domain.Video{}, false, nil
	}
	if err != nil {
		return domain.Video{}, false, err
	}
	video.PosterPath = posterPath
	video.UpdatedAt = parseTimeOrNow(updatedRaw)

	subs, err := s.listSubtitlesByVideoID(video.ID)
	if err != nil {
		return domain.Video{}, false, err
	}
	video.Subtitles = subs
	return video, true, nil
}

func (s *Store) UpdateVideoSubtitles(videoID string, subtitles []domain.Subtitle, updatedAt time.Time) error {
	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	defer func() {
		if err != nil {
			_ = tx.Rollback()
		}
	}()

	res, err := s.execTx(tx, `UPDATE videos SET updated_at = ? WHERE id = ?`, updatedAt.UTC().Format(time.RFC3339Nano), videoID)
	if err != nil {
		return err
	}
	affected, err := res.RowsAffected()
	if err != nil {
		return err
	}
	if affected == 0 {
		return sql.ErrNoRows
	}

	existingSubtitleSources, err := s.loadSubtitleSourcesTx(tx, videoID)
	if err != nil {
		return err
	}
	if _, err = s.execTx(tx, `DELETE FROM subtitles WHERE video_id = ?`, videoID); err != nil {
		return err
	}
	for _, sub := range subtitles {
		sub = mergeSubtitleSource(sub, existingSubtitleSources)
		_, err = s.execTx(
			tx,
			`INSERT INTO subtitles(id, video_id, path, file_name, language, format, size, mod_time, updated_at, source, source_detail)
VALUES(?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
			sub.ID,
			videoID,
			sub.Path,
			sub.FileName,
			sub.Language,
			sub.Format,
			sub.Size,
			sub.ModTime.UTC().Format(time.RFC3339Nano),
			updatedAt.UTC().Format(time.RFC3339Nano),
			sub.Source,
			sub.SourceDetail,
		)
		if err != nil {
			return err
		}
	}
	return tx.Commit()
}

